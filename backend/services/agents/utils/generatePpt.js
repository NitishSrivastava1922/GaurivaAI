import pptxgen from "pptxgenjs"

const COLORS = {
    primary: "2563EB",
    secondary: "0F172A",
    text: "334155",
    light: "F8FAFC",
    border: "E2E8F0",
    white: "FFFFFF",
    muted: "64748B",
}

export const generatePpt = async (data) => {
    const ppt = new pptxgen()

    ppt.layout = "LAYOUT_WIDE"
    ppt.author = "NexusAi"
    ppt.company = "NexusAi"
    ppt.title = data.title
    ppt.subject = data.title
    ppt.lang = "en-US"

    ppt.theme = {
        headFontFace: "Aptos",
        bodyFontFace: "Aptos",
        lang: "en-US",
    }

    addCover(ppt, data)

    data?.slides?.forEach((slide, index) => {
        addContentSlide(
            ppt,
            slide.title,
            slide.points,
            index + 1,
            data.slides.length
        )
    })

    addThankYou(ppt)

    return ppt
}

const addCover = (ppt, data) => {
    const slide = ppt.addSlide()

    slide.background = {
        color: COLORS.primary,
    }

    slide.addShape(ppt.ShapeType.rect, {
        x: 0,
        y: 0,
        w: 13.33,
        h: 0.18,
        fill: {
            color: "60A5FA",
        },
        line: {
            color: "60A5FA",
        },
    })

    slide.addText(data.title, {
        x: 0.7,
        y: 1.6,
        w: 12,
        h: 0.8,
        align: "center",
        bold: true,
        color: COLORS.white,
        fontSize: 28,
    })

    slide.addText(data.subtitle, {
        x: 1,
        y: 2.7,
        w: 11.5,
        h: 0.5,
        align: "center",
        color: "DBEAFE",
        fontSize: 15,
    })

    slide.addText("Generated By NexusAi", {
        x: 0,
        y: 6.9,
        w: 13.33,
        h: 0.2,
        align: "center",
        color: "BFDBFE",
        fontSize: 10,
    })
}
const addContentSlide = (ppt, title, points, page, total) => {
    const slide = ppt.addSlide()

    slide.background = {
        color: COLORS.white,
    }

    slide.addText(title, {
        x: 0.6,
        y: 0.35,
        w: 10,
        h: 0.45,
        fontSize: 24,
        bold: true,
        color: COLORS.primary,
    })

    slide.addShape(ppt.ShapeType.line, {
        x: 0.6,
        y: 0.9,
        w: 12,
        h: 0,
        line: {
            color: COLORS.border,
            width: 1.2,
        },
    })

    const visiblePoints = (points || []).slice(0, 6)

    visiblePoints.forEach((point, i) => {
        const y = 1.2 + i * 0.75

        slide.addShape(ppt.ShapeType.roundRect, {
            x: 0.75,
            y,
            w: 11.8,
            h: 0.58,
            radius: 0.08,
            fill: {
                color: i % 2 === 0 ? "EFF6FF" : "F8FAFC",
            },
            line: {
                color: COLORS.border,
            },
        })

        slide.addShape(ppt.ShapeType.ellipse, {
            x: 0.92,
            y: y + 0.18,
            w: 0.12,
            h: 0.12,
            fill: {
                color: COLORS.primary,
            },
            line: {
                color: COLORS.primary,
            },
        })

        slide.addText(point, {
            x: 1.2,
            y: y + 0.08,
            w: 11,
            h: 0.35,
            fontSize: 15,
            color: COLORS.text,
            fit: "shrink",
            margin: 0,
        })
    })

    slide.addShape(ppt.ShapeType.line, {
        x: 0.6,
        y: 6.9,
        w: 12,
        h: 0,
        line: {
            color: COLORS.border,
            width: 1,
        },
    })

    slide.addText("Generated by NexusAi", {
        x: 0.6,
        y: 7.0,
        w: 2.8,
        h: 0.18,
        color: COLORS.muted,
        fontSize: 9,
    })

    slide.addText(`${page}/${total}`, {
        x: 11.8,
        y: 7.0,
        w: 0.7,
        h: 0.18,
        align: "right",
        color: COLORS.muted,
        fontSize: 9,
    })
}
const addThankYou = (ppt) => {
    const slide = ppt.addSlide()

    slide.background = {
        color: COLORS.secondary,
    }

    slide.addText("Thank You", {
        x: 1,
        y: 2.1,
        w: 11.3,
        h: 0.8,
        align: "center",
        bold: true,
        color: COLORS.white,
        fontSize: 30,
    })

    slide.addText("Questions?", {
        x: 1,
        y: 3.1,
        w: 11.3,
        h: 0.4,
        align: "center",
        color: "CBD5E1",
        fontSize: 18,
    })

    slide.addText("Generated By NexusAi", {
        x: 0,
        y: 6.9,
        w: 13.33,
        h: 0.2,
        align: "center",
        color: "94A3B8",
        fontSize: 10,
    })
}